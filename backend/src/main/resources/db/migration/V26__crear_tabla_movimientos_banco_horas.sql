CREATE TABLE movimientos_banco_horas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id BIGINT NOT NULL,
    sesion_trabajo_id BIGINT,
    minutos INT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    liquidado BOOLEAN NOT NULL DEFAULT FALSE,
    liquidacion_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT fk_mov_banco_horas_usuario FOREIGN KEY (empleado_id) REFERENCES usuarios(id),
    CONSTRAINT fk_mov_banco_horas_sesion FOREIGN KEY (sesion_trabajo_id) REFERENCES sesiones_trabajo(id)
);

CREATE INDEX idx_mov_banco_horas_empleado_liquidado ON movimientos_banco_horas(empleado_id, liquidado);
