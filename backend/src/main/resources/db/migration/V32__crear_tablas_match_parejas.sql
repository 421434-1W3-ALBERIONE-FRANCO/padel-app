-- Match de parejas: perfil deportivo del jugador, su disponibilidad semanal por bloques,
-- las respuestas a cada tarjeta (me interesa / paso) y los matches mutuos.
CREATE TABLE perfiles_jugador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    categoria VARCHAR(20) NOT NULL,
    posicion VARCHAR(20) NOT NULL,
    bio VARCHAR(280),
    visible_en_match BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT uk_perfiles_jugador_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_perfiles_jugador_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);

CREATE TABLE disponibilidades_jugador (
    perfil_id BIGINT NOT NULL,
    dia_semana VARCHAR(10) NOT NULL,
    bloque VARCHAR(10) NOT NULL,
    CONSTRAINT pk_disponibilidades_jugador PRIMARY KEY (perfil_id, dia_semana, bloque),
    CONSTRAINT fk_disponibilidades_perfil FOREIGN KEY (perfil_id) REFERENCES perfiles_jugador(id) ON DELETE CASCADE
);

CREATE TABLE match_swipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origen_id BIGINT NOT NULL,
    destino_id BIGINT NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT uk_match_swipes_origen_destino UNIQUE (origen_id, destino_id),
    CONSTRAINT fk_match_swipes_origen FOREIGN KEY (origen_id) REFERENCES usuarios(id),
    CONSTRAINT fk_match_swipes_destino FOREIGN KEY (destino_id) REFERENCES usuarios(id)
);

CREATE INDEX idx_match_swipes_destino ON match_swipes(destino_id);

CREATE TABLE match_parejas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jugador1_id BIGINT NOT NULL,
    jugador2_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT uk_match_parejas UNIQUE (jugador1_id, jugador2_id),
    CONSTRAINT fk_match_parejas_jugador1 FOREIGN KEY (jugador1_id) REFERENCES usuarios(id),
    CONSTRAINT fk_match_parejas_jugador2 FOREIGN KEY (jugador2_id) REFERENCES usuarios(id)
);

CREATE INDEX idx_match_parejas_jugador2 ON match_parejas(jugador2_id);
