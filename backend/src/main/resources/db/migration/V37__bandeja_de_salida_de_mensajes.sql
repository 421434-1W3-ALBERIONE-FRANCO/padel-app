-- Bandeja de salida (Transactional Outbox) de emails y WhatsApp: se escriben en la misma transacción que el
-- cambio de negocio y un proceso los envía con reintentos.
CREATE TABLE mensajes_salientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    canal VARCHAR(20) NOT NULL,
    destinatario VARCHAR(150) NOT NULL,
    asunto VARCHAR(200),
    cuerpo TEXT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    intentos INT NOT NULL DEFAULT 0,
    proximo_intento_en TIMESTAMP NOT NULL,
    enviado_en TIMESTAMP,
    ultimo_error VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

-- El despachador busca los pendientes cuyo próximo intento ya llegó.
CREATE INDEX idx_mensajes_salientes_pendientes ON mensajes_salientes (estado, proximo_intento_en);
