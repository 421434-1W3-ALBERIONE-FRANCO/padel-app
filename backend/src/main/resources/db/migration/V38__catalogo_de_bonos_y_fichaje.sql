-- 3) Fichaje explícito: un empleado tiene a lo sumo una jornada abierta (un doble click en "fichar entrada"
--    abría dos). Si quedaron duplicadas de antes, se conserva la más reciente.
UPDATE sesiones_trabajo s
   SET estado = 'CERRADA', fin = s.inicio, minutos_trabajados = 0, cerrada_automaticamente = TRUE
 WHERE s.estado = 'ABIERTA'
   AND EXISTS (SELECT 1 FROM sesiones_trabajo o WHERE o.empleado_id = s.empleado_id AND o.estado = 'ABIERTA' AND o.id > s.id);
CREATE UNIQUE INDEX ux_sesiones_trabajo_una_abierta ON sesiones_trabajo (empleado_id) WHERE estado = 'ABIERTA';
