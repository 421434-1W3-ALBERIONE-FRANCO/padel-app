-- 1) Catálogo de bonos administrado por el ADMIN. Antes los packs estaban fijos en el frontend y quien
--    vendía podía cambiar horas y precio a mano. Se cargan los mismos packs que ofrecía la pantalla de venta.
CREATE TABLE tipos_bono (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    nombre VARCHAR(50) NOT NULL,
    descripcion VARCHAR(255),
    horas INT NOT NULL CHECK (horas > 0),
    precio DECIMAL(10,2) NOT NULL CHECK (precio >= 0),
    dias_vigencia INT NOT NULL CHECK (dias_vigencia > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    created_by VARCHAR(50),
    updated_by VARCHAR(50),
    CONSTRAINT uk_tipos_bono_nombre UNIQUE (nombre)
);

