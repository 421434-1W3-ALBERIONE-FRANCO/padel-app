CREATE TABLE sesiones_trabajo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id BIGINT NOT NULL,
    inicio TIMESTAMP NOT NULL,
    fin TIMESTAMP,
    minutos_trabajados INT,
    cerrada_automaticamente BOOLEAN NOT NULL DEFAULT FALSE,
    estado VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT fk_sesiones_trabajo_usuario FOREIGN KEY (empleado_id) REFERENCES usuarios(id)
);

CREATE INDEX idx_sesion_empleado_estado ON sesiones_trabajo(empleado_id, estado);
