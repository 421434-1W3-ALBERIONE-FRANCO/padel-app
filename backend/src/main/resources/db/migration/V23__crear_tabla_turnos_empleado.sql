CREATE TABLE turnos_empleado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id BIGINT NOT NULL,
    dia_semana VARCHAR(20) NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT fk_turnos_empleado_usuario FOREIGN KEY (empleado_id) REFERENCES usuarios(id),
    CONSTRAINT uk_turno_empleado_dia UNIQUE (empleado_id, dia_semana)
);

CREATE INDEX idx_turnos_empleado ON turnos_empleado(empleado_id);
