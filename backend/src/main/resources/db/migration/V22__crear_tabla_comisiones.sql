CREATE TABLE comisiones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recepcionista_id BIGINT NOT NULL,
    origen VARCHAR(20) NOT NULL,
    pago_id BIGINT,
    bono_id BIGINT,
    monto_base DECIMAL(10,2) NOT NULL,
    porcentaje_aplicado DECIMAL(5,2) NOT NULL,
    monto_comision DECIMAL(10,2) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT fk_comisiones_recepcionista FOREIGN KEY (recepcionista_id) REFERENCES usuarios(id),
    CONSTRAINT fk_comisiones_pago FOREIGN KEY (pago_id) REFERENCES pagos(id),
    CONSTRAINT fk_comisiones_bono FOREIGN KEY (bono_id) REFERENCES bonos(id)
);

CREATE INDEX idx_comisiones_recepcionista_estado ON comisiones(recepcionista_id, estado);
