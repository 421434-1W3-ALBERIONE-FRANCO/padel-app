CREATE TABLE liquidaciones_sueldo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id BIGINT NOT NULL,
    periodo_desde DATE NOT NULL,
    periodo_hasta DATE NOT NULL,
    total_minutos_trabajados INT NOT NULL,
    total_minutos_banco_horas INT NOT NULL,
    total_comisiones DECIMAL(10,2) NOT NULL,
    generada_por_id BIGINT NOT NULL,
    generada_en TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT fk_liquidacion_empleado FOREIGN KEY (empleado_id) REFERENCES usuarios(id),
    CONSTRAINT fk_liquidacion_generada_por FOREIGN KEY (generada_por_id) REFERENCES usuarios(id)
);

CREATE INDEX idx_liquidacion_empleado ON liquidaciones_sueldo(empleado_id);

-- Vincular comisiones y movimientos de banco de horas a la liquidación que los salda.
ALTER TABLE comisiones ADD COLUMN liquidacion_id BIGINT;
ALTER TABLE comisiones ADD CONSTRAINT fk_comisiones_liquidacion FOREIGN KEY (liquidacion_id) REFERENCES liquidaciones_sueldo(id);

ALTER TABLE movimientos_banco_horas ADD CONSTRAINT fk_mov_banco_horas_liquidacion FOREIGN KEY (liquidacion_id) REFERENCES liquidaciones_sueldo(id);
